/** Pixel sizes of the screenshots that are not a whole 1440 × 960 window. */
const SIZES: Record<string, [number, number]> = { hub: [1440, 765], 'task-hint-panel': [1152, 720] };

/** Width and height of a screenshot, so the page keeps its place before the picture loads. */
export function shotSize(name: string): [number, number] {
	return SIZES[name] ?? [1440, 960];
}

const urls = import.meta.glob('./shots/*/*.webp', { eager: true, query: '?url', import: 'default' }) as Record<string, string>;

/** The screenshot in the interface language, or the Russian one when there is no other. */
export function shotUrl(name: string): string {
	return urls[`./shots/${i18n.lang}/${name}.webp`] ?? urls[`./shots/ru/${name}.webp`] ?? '';
}
